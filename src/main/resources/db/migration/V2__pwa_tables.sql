-- Fat Fish: tablas de la PWA (modelo del README de fat-fish-pwa, con id numérico)

create table jugador(id bigint generated by default as identity primary key,
alias varchar(24) not null,
creado_en timestamptz not null default now());

create table partida(id bigint generated by default as identity primary key,
jugador_id bigint not null references jugador(id),
resultado varchar(10) not null check (resultado in ('VICTORIA', 'DERROTA', 'ABANDONO')),
ronda_alcanzada int not null check (ronda_alcanzada between 1 and 9),
puntaje int not null check (puntaje >= 0),
dinero_invertido int not null check (dinero_invertido >= 0),
dinero_ganado int not null check (dinero_ganado >= 0),
dinero_perdido int not null check (dinero_perdido >= 0),
duracion_seg int not null check (duracion_seg >= 0),
creada_en timestamptz not null default now());

create index idx_partida_jugador on partida(jugador_id, creada_en desc);

-- Retroalimentación enviada desde la PWA (solo inserción, anónima).
-- clave_idempotencia la genera la PWA en cada envío; si un reintento repite la clave, no se guarda dos veces.
create table retroalimentacion(id bigint generated by default as identity primary key,
clave_idempotencia uuid unique,
categoria varchar(20) not null check (categoria in ('ERROR', 'SUGERENCIA', 'OTRO')),
componente varchar(20) not null check (componente in ('JUEGO', 'PWA', 'OTRO')),
mensaje varchar(1000) not null check (char_length(btrim(mensaje)) >= 10),
creada_en timestamptz not null default now());
