create table jugador(id bigint generated by default as identity primary key,
alias varchar(24) not null,
contrasena_hash varchar(60) not null,
token_hash varchar(64) not null unique,
creado_en timestamptz not null default now(),
ultima_actividad timestamptz);
create index idx_jugador_alias on jugador(lower(alias));

create table estadistica_jugador(jugador_id bigint primary key references jugador(id),
puntaje_maximo int not null default 0,
puntaje_maximo_en timestamptz,
partidas_totales int not null default 0,
partidas_ganadas int not null default 0,
dinero_invertido int not null default 0,
dinero_ganado int not null default 0,
dinero_perdido int not null default 0,
racha_derrotas_max int not null default 0,
tiempo_jugado_seg int not null default 0);
create index idx_estadistica_ranking on estadistica_jugador(puntaje_maximo desc, puntaje_maximo_en)
where puntaje_maximo_en is not null;

create table partida(id bigint generated by default as identity primary key,
jugador_id bigint not null references jugador(id),
numero_local int not null check (numero_local >= 1),
resultado varchar(10) not null check (resultado in ('VICTORIA', 'DERROTA', 'ABANDONO')),
ronda_alcanzada int not null check (ronda_alcanzada between 1 and 9),
puntaje int not null check (puntaje >= 0),
dinero_invertido int not null check (dinero_invertido >= 0),
dinero_ganado int not null check (dinero_ganado >= 0),
dinero_perdido int not null check (dinero_perdido >= 0),
veces_todo_o_nada int not null check (veces_todo_o_nada >= 0),
empenos int not null check (empenos >= 0),
prestamos int not null check (prestamos >= 0),
duracion_seg int not null check (duracion_seg >= 0),
creada_en timestamptz not null default now(),
unique (jugador_id, numero_local));
create index idx_partida_jugador on partida(jugador_id, creada_en desc);

create table comodin(id smallint primary key,
nombre varchar(40) not null unique,
descripcion varchar(200) not null);

create table partida_comodin(partida_id bigint not null references partida(id) on delete cascade,
comodin_id smallint not null references comodin(id),
veces_comprado int not null check (veces_comprado >= 0),
veces_usado int not null check (veces_usado >= 0),
primary key (partida_id, comodin_id));

create table retroalimentacion(id bigint generated by default as identity primary key,
clave_idempotencia uuid not null unique,
categoria varchar(20) not null check (categoria in ('ERROR', 'SUGERENCIA', 'OTRO')),
componente varchar(20) not null check (componente in ('JUEGO', 'PWA', 'OTRO')),
mensaje varchar(1000) not null check (char_length(btrim(mensaje)) >= 10),
creada_en timestamptz not null default now());

create table encuesta(id bigint generated by default as identity primary key,
clave_idempotencia uuid not null unique,
percepcion_riesgo smallint not null check (percepcion_riesgo between 1 and 5),
cambio_opinion smallint not null check (cambio_opinion between 1 and 5),
claridad_mensaje smallint not null check (claridad_mensaje between 1 and 5),
comentario varchar(500),
enviada_en timestamptz not null default now());

